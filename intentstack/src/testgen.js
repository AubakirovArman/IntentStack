function samplePayload(entity, opts = {}) {
  const out = {}
  for (const field of entity.fields || []) {
    if (opts.partial && field.required !== true) continue
    out[field.id] = sampleValue(field)
  }
  return out
}

function sampleValue(field) {
  if (field.type === 'number') return 1
  if (field.type === 'boolean') return true
  if (field.type === 'datetime') return '2026-01-01T00:00:00.000Z'
  if (field.type === 'enum') return field.values?.[0] || 'new'
  if (field.type === 'text') return `Generated ${field.label || field.id}`
  return `Generated ${field.label || field.id}`
}

function envName(value) {
  return String(value || 'record').replace(/[^a-z0-9]+/gi, '_').replace(/^_|_$/g, '').toUpperCase() || 'RECORD'
}
