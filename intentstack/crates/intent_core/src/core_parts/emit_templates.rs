fn web_routes_tsx(graph: &AppGraph) -> String {
    let imports = graph
        .pages
        .iter()
        .map(|page| {
            format!(
                "import {{ {}Page }} from './generated/pages/{}Page'",
                pascal(&page.id),
                pascal(&page.id)
            )
        })
        .collect::<Vec<_>>()
        .join("\n");
    let branches = graph
        .pages
        .iter()
        .skip(1)
        .map(|page| {
            format!(
                "  if (path === {}) return <{}Page />",
                js_str(&page.path),
                pascal(&page.id)
            )
        })
        .collect::<Vec<_>>()
        .join("\n");
    let first = graph
        .pages
        .first()
        .map(|page| pascal(&page.id))
        .unwrap_or_else(|| "Home".to_string());
    format!(
        "{RUST_EMIT_BANNER}{imports}\n\nexport function App() {{\n  const path = window.location.pathname\n{branches}\n  return <{first}Page />\n}}\n"
    )
}
