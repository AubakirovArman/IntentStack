const RUST_EMIT_BANNER: &str = "// @generated by IntentStack Rust core. Do not edit by hand.\n\n";

fn emit_file_content(graph: &AppGraph, file: &PlannedFile) -> String {
    match graph.project.target.as_str() {
        "web_ts_minimal" => emit_web_file(graph, file),
        "next_shadcn" => emit_next_file(graph, file),
        _ => format!(
            "{RUST_EMIT_BANNER}// Unsupported target {}\n",
            graph.project.target
        ),
    }
}

